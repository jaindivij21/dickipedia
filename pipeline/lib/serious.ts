export function normSection(raw: string): string | null {
  const m = raw
    .trim()
    .toUpperCase()
    .match(/^\(?(\d+[A-Z]?)/);
  return m ? m[1] : null;
}

export function isSeriousCase(sections: readonly string[]): boolean {
  return sections.some((s) => {
    const b = normSection(s);
    return b != null && SERIOUS_IPC_SECTIONS.has(b);
  });
}
